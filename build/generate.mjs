#!/usr/bin/env node
/**
 * BUILD-TIME PRE-RENDER  —  node build/generate.mjs
 * ==================================================
 *
 * Fetches the same two published Google Sheet CSVs the browser requests, and
 * injects the rendered event + article markup into the HTML so crawlers see
 * real content on the first byte instead of a "Loading..." placeholder.
 *
 * THE ONE SOURCE OF TRUTH
 * -----------------------
 * This script imports js/shared/data.js — the exact module js/events.js and
 * js/articles.js import in the browser — so the HTML written here and the HTML
 * the client script would produce are generated by the same functions and
 * cannot drift. If you change card markup, change it there; both follow.
 *
 * SHEET URLS
 * ----------
 * Read from the live [[redirects]] rules in netlify.toml (the same 'to' URLs
 * Netlify proxies for the browser). Change a sheet by editing netlify.toml —
 * this script needs no edits. Overridable with PMNZ_SHEET_OVERRIDE_JSON for
 * local testing without touching the config.
 *
 * NEVER FAILS A DEPLOY
 * --------------------
 * A flaky Sheet, a Google outage or a bad response must never break the site
 * build. On any fetch/parse error this script logs a clear warning, leaves the
 * previous generated markup (or the original placeholder) exactly as it is,
 * and exits 0. Node's stdlib only — no dependencies to install.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  parseEventRows,
  parsePossibilitatorRows,
  renderEventSectionsHTML,
  renderPossibilitatorCardsHTML,
  contentSignature,
} from '../js/shared/data.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const FETCH_TIMEOUT_MS = 20_000;
const USER_AGENT = 'PMNZ-Website-Build/1.0 (+https://possibilitymanagement.co.nz)';

/**
 * The build targets. `sheetKey` matches a `from` path in netlify.toml and
 * `mountId` matches the element the client script renders into, so the
 * generated markup and the runtime markup are interchangeable.
 */
const TARGETS = [
  {
    sheetKey: '/api/pm-events.csv',
    page: 'index.html',
    mountId: 'pm-events',
    parse: parseEventRows,
    render: (rows) => renderEventSectionsHTML(rows),
    count: (html) => (html.match(/event-card-title/g) || []).length,
  },
  {
    sheetKey: '/api/possibilitators.csv',
    page: 'articles.html',
    mountId: 'possibilitators-grid',
    parse: parsePossibilitatorRows,
    render: (rows) => renderPossibilitatorCardsHTML(rows),
    count: (html) => (html.match(/possibilitator-card/g) || []).length,
  },
];

const log = (...args) => console.log('[build:prerender]', ...args);
const warn = (...args) => console.warn('[build:prerender] WARNING:', ...args);

/**
 * Pull the live CSV source URLs out of netlify.toml's [[redirects]] rules.
 * We deliberately parse only the `from`/`to` string pairs rather than pulling
 * in a TOML parser — no dependencies — and we only care about the CSV proxy
 * rules, which is a stable, tiny slice of the file.
 *
 * @returns {Promise<Record<string,string>>} map of `from` path -> `to` URL
 */
async function readSheetUrls() {
  const toml = await readFile(join(ROOT, 'netlify.toml'), 'utf8');

  const urls = {};
  const blockRe = /\[\[redirects\]\]([\s\S]*?)(?=\n\[\[|\n#|\s*$)/g;
  let block;
  while ((block = blockRe.exec(toml)) !== null) {
    const from = block[1].match(/^\s*from\s*=\s*"([^"]+)"/m);
    const to = block[1].match(/^\s*to\s*=\s*"([^"]+)"/m);
    if (from && to) urls[from[1]] = to[1];
  }

  // Test-only escape hatch so the failure path can be exercised locally
  // without editing the committed config.
  const override = process.env.PMNZ_SHEET_OVERRIDE_JSON;
  if (override) Object.assign(urls, JSON.parse(override));

  return urls;
}

/**
 * Fetch a published Sheet CSV with a timeout.
 * Any failure (network, DNS, non-2xx, timeout) throws so the caller can fall
 * back to leaving the page untouched.
 *
 * @param {string} url
 * @returns {Promise<string>} raw CSV text
 */
async function fetchCsv(url) {
  const res = await fetch(url, {
    redirect: 'follow', // published CSVs answer with a 307
    headers: { 'User-Agent': USER_AGENT, Accept: 'text/csv,text/plain,*/*' },
    signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
  });
  if (!res.ok) throw new Error(`HTTP ${res.status} ${res.statusText}`.trim());
  return await res.text();
}

/* ==========================================================
   HTML INJECTION
   ========================================================== */

/**
 * Build the marker comments that delimit generated content inside a mount.
 * They are emitted by hand into the HTML and are the only thing this script
 * edits, so hand-written markup around them is never touched.
 */
function marker(id, which) {
  return `<!-- build:${id}:${which} -->`;
}

/**
 * Replace the content between `<!-- build:<id>:start -->` and
 * `<!-- build:<id>:end -->` with `content`, re-indenting to match.
 *
 * Returns null (rather than throwing) when the markers are missing, so a page
 * that has not opted in is skipped instead of failing the build.
 *
 * @returns {string|null} updated HTML, or null if no markers found
 */
export function injectIntoMount(html, id, content) {
  const start = marker(id, 'start');
  const end = marker(id, 'end');

  const startIdx = html.indexOf(start);
  const endIdx = html.indexOf(end);
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) return null;

  const before = html.slice(0, startIdx + start.length);
  const after = html.slice(endIdx);

  // Re-indent generated lines to sit under the opening marker.
  const lineStart = before.lastIndexOf('\n') + 1;
  const indent = (before.slice(lineStart).match(/^[ \t]*/) || [''])[0];

  const body = content
    .split('\n')
    .map((line) => (line.trim() ? indent + line : line))
    .join('\n');

  return `${before}\n${body}\n${indent}${after}`;
}

/**
 * Stamp the mount element with a signature of what was rendered.
 *
 * The client script renders the same HTML and compares signatures. If they
 * match, the pre-rendered DOM is already correct and is left untouched — no
 * flash, no re-triggered scroll animations. If they differ (someone edited
 * the Sheet after the last deploy), the client refreshes the content as it
 * always did.
 *
 * @returns {string|null} updated HTML, or null if the mount element is absent
 */
export function stampSignature(html, id, signature) {
  const re = new RegExp(`(<div[^>]*id=["']${id}["'][^>]*)(>)`, 'i');
  const match = html.match(re);
  if (!match) return null;

  const openTag = match[1].replace(/\s*data-signature=["'][^"']*["']/gi, '');
  return html.replace(re, `${openTag} data-signature="${signature}"${match[2]}`);
}

/* ==========================================================
   MAIN
   ========================================================== */

/**
 * Pre-render one target into its page.
 *
 * Never throws: every failure path warns and leaves the page's existing
 * content in place, then reports the outcome.
 *
 * @returns {Promise<'updated'|'unchanged'|'skipped'|'failed'>}
 */
async function processTarget(target, url) {
  const pagePath = join(ROOT, target.page);

  let html = await readFile(pagePath, 'utf8');

  // 1. Fetch. Anything can go wrong here (offline, 500, timeout, DNS).
  let csv;
  try {
    csv = await fetchCsv(url);
  } catch (err) {
    warn(`${target.sheetKey} could not be fetched (${err.message}).`);
    warn(`Leaving ${target.page} untouched — the browser will still fetch and render it live.`);
    return 'failed';
  }

  // 2. Parse. A Sheet can serve an HTML error/sign-in page with a 200 status,
  //    which would otherwise be injected as garbage.
  let rows;
  try {
    rows = target.parse(csv);
    if (!rows.length) throw new Error('no data rows');
  } catch (err) {
    warn(`${target.sheetKey} could not be parsed (${err.message}).`);
    warn(`Leaving ${target.page} untouched — the browser will still fetch and render it live.`);
    return 'failed';
  }

  // 3. Render, using the same functions the browser scripts use.
  let content;
  try {
    content = target.render(rows);
  } catch (err) {
    warn(`${target.page} could not be rendered (${err.message}). Leaving it untouched.`);
    return 'failed';
  }

  // 4. Inject between the build markers.
  const withContent = injectIntoMount(html, target.mountId, content);
  if (withContent === null) {
    warn(`${target.page} has no "${marker(target.mountId, 'start')}" markers — skipped.`);
    return 'skipped';
  }

  // 5. Stamp the signature so the client script can skip redundant re-renders.
  const finalHtml = stampSignature(withContent, target.mountId, contentSignature(content));
  if (finalHtml === null) {
    warn(`${target.page} has no element with id="${target.mountId}" — skipped.`);
    return 'skipped';
  }

  if (finalHtml === html) {
    log(`${target.page} already up to date (${target.count(content)} items).`);
    return 'unchanged';
  }

  await writeFile(pagePath, finalHtml, 'utf8');
  log(`${target.page}: pre-rendered ${target.count(content)} item(s) into #${target.mountId}.`);
  return 'updated';
}

async function main() {
  let urls;
  try {
    urls = await readSheetUrls();
  } catch (err) {
    warn(`Could not read netlify.toml (${err.message}). Nothing was pre-rendered.`);
    return;
  }

  for (const target of TARGETS) {
    const url = urls[target.sheetKey];
    if (!url) {
      warn(`No redirect for ${target.sheetKey} in netlify.toml — skipped.`);
      continue;
    }
    try {
      await processTarget(target, url);
    } catch (err) {
      // Belt and braces: a page that throws for any unforeseen reason must
      // still not take the deploy down with it.
      warn(`${target.page} failed unexpectedly (${err.message}). Leaving it untouched.`);
    }
  }
}

// The build must never fail the deploy. Exit 0 even on unexpected errors.
main()
  .catch((err) => {
    warn(`Unexpected error: ${err && err.stack ? err.stack : err}`);
  })
  .finally(() => {
    log('done — build exiting 0.');
    process.exit(0);
  });
